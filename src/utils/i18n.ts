const format = (template: string, vars: Record<string, string | number>) =>
  template.replace(/\{(\w+)\}/g, (_, key) =>
    vars[key] !== undefined ? String(vars[key]) : ""
  );

export const t = (lang: Lang, key: string, vars?: Record<string, string | number>) => {
  const fallback = I18N[DEFAULT_LANG][key] ?? key;
  const template = I18N[lang]?.[key] ?? fallback;
  return vars ? format(template, vars) : template;
};
